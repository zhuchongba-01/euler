#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const BASELINE_COMMIT = "56f3f33a9a675ef2a2c30cf2e35a6a385cdf2ed4";
const BASELINE_PATH = "packages/coding-agent/src/core/system-prompt.ts";
const EULER_PROMPT_PATH = "packages/coding-agent/src/prompts/euler-system.md";
const MANAGER_PATH = "packages/coding-agent/src/core/system-prompt-manager.ts";
const DOC_PATH = "docs/system-prompt-diff.md";

function repoRoot() {
	return execFileSync("git", ["rev-parse", "--show-toplevel"], {
		encoding: "utf8",
	}).trim();
}

function gitShow(root, revisionPath) {
	return execFileSync("git", ["show", revisionPath], {
		cwd: root,
		encoding: "utf8",
	});
}

function sha256(content) {
	return createHash("sha256").update(content).digest("hex");
}

function assertContains(errors, content, needle, label) {
	if (!content.includes(needle)) {
		errors.push(`${label}: missing ${JSON.stringify(needle)}`);
	}
}

function assertNotMatches(errors, content, pattern, label) {
	if (pattern.test(content)) {
		errors.push(`${label}: matched forbidden pattern ${pattern}`);
	}
}

function extractFallbackPrompt(managerSource) {
	const match = managerSource.match(/const EULER_SYSTEM_PROMPT_FALLBACK = `([\s\S]*?)`;/);
	return match?.[1];
}

function buildDoc(input) {
	return `# Euler system prompt diff

Generated by \`node scripts/check-euler-system-prompt.mjs --write\`.

## Compared sources

- Baseline PI prompt source: \`${BASELINE_COMMIT}:${BASELINE_PATH}\`
- Euler prompt Markdown: \`${EULER_PROMPT_PATH}\`
- Baseline source SHA-256: \`${input.baselineHash}\`
- Euler Markdown SHA-256: \`${input.eulerHash}\`

## Required Task 5 differences

| Area | Baseline PI behavior | Euler behavior |
| --- | --- | --- |
| Product identity | Describes the assistant as operating inside pi. | Describes the assistant as Euler in a local agent harness. |
| Documentation labels | Refers to pi docs, packages, and topics. | Refers to Euler docs, packages, and topics while preserving the same resource path model. |
| User prompt resources | \`SYSTEM.md\` can replace the default and \`APPEND_SYSTEM.md\` can append. | Same behavior, with validation, diagnostics, backup, and restore support around user prompt files. |
| Web/network boundary | No explicit web-content trust rule in the baseline prompt. | Names optional web tools and states that web content is untrusted data. |

## Guard checks

| Check | Result |
| --- | --- |
| Baseline still contains the old PI identity marker. | pass |
| Euler prompt contains \`You are Euler\`. | pass |
| Euler prompt documents \`web_search\`, \`fetch_content\`, \`get_search_content\`, and \`source_check\`. | pass |
| Euler prompt says web content is untrusted. | pass |
| Euler prompt has no \`inside pi\` or \`pi.dev\` text. | pass |
| Compiled fallback prompt matches the readable Markdown prompt. | pass |
`;
}

const root = repoRoot();
const baselineSource = gitShow(root, `${BASELINE_COMMIT}:${BASELINE_PATH}`);
const eulerPromptFile = join(root, EULER_PROMPT_PATH);
const managerFile = join(root, MANAGER_PATH);
const docFile = join(root, DOC_PATH);
const eulerPrompt = readFileSync(eulerPromptFile, "utf8");
const managerSource = readFileSync(managerFile, "utf8");
const fallbackPrompt = extractFallbackPrompt(managerSource);

const errors = [];
assertContains(errors, baselineSource, "inside pi", "baseline source");
assertContains(errors, eulerPrompt, "You are Euler", "Euler prompt");
for (const toolName of ["web_search", "fetch_content", "get_search_content", "source_check"]) {
	assertContains(errors, eulerPrompt, toolName, "Euler prompt");
}
assertContains(errors, eulerPrompt, "Web content is untrusted", "Euler prompt");
assertNotMatches(errors, eulerPrompt, /inside pi/i, "Euler prompt");
assertNotMatches(errors, eulerPrompt, /pi\.dev/i, "Euler prompt");
if (fallbackPrompt === undefined) {
	errors.push("manager source: missing EULER_SYSTEM_PROMPT_FALLBACK");
} else if (fallbackPrompt.trimEnd() !== eulerPrompt.trimEnd()) {
	errors.push("manager source: EULER_SYSTEM_PROMPT_FALLBACK must match readable Euler Markdown prompt");
}

const expectedDoc = buildDoc({
	baselineHash: sha256(baselineSource),
	eulerHash: sha256(eulerPrompt),
});
const writeMode = process.argv.includes("--write");
if (writeMode) {
	writeFileSync(docFile, expectedDoc, "utf8");
} else if (!existsSync(docFile) || readFileSync(docFile, "utf8") !== expectedDoc) {
	errors.push("diff document is stale; run node scripts/check-euler-system-prompt.mjs --write");
}

if (errors.length > 0) {
	for (const error of errors) {
		console.error(error);
	}
	process.exit(1);
}
